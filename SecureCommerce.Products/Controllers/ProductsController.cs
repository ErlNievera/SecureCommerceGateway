
using Microsoft.AspNetCore.Mvc;
using SecureCommerce.Products.Models;

namespace SecureCommerce.Products.Controllers;

[ApiController]
[Route("api/[controller]")]
public class ProductsController : ControllerBase
{
    private static readonly List<Product> Products = new()
    {
        new Product
        {
            Id = 1,
            Name = "Mechanical Keyboard",
            Price = 2499.00m,
            Stock = 10
        },
        new Product
        {
            Id = 2,
            Name = "USB Cable",
            Price = 199.00m,
            Stock = 25
        }
    };

    private static int _nextId = 3;

    [HttpGet]
    public ActionResult<IEnumerable<Product>> GetAll()
    {
        Console.WriteLine($"Products count: {Products.Count}");
        return Ok(Products);
    }

    [HttpGet("{id:int}")]
    public ActionResult<Product> GetById(int id)
    {
        Product? product = Products.FirstOrDefault(p => p.Id == id);

        if (product == null)
        {
            return NotFound();
        }

        return Ok(product);
    }

    [HttpPost]
    public ActionResult<Product> Create(Product product)
    {
        if (product.Id != 0)
        {
            return BadRequest("The product ID is generated by the API.");
        }

        if (string.IsNullOrWhiteSpace(product.Name) ||
            product.Price < 0 ||
            product.Stock < 0)
        {
            return BadRequest("Invalid product data.");
        }

        product.Id = _nextId++;
        Products.Add(product);

        return CreatedAtAction(
            nameof(GetById),
            new { id = product.Id },
            product);
    }


    [HttpPut("{id:int}")]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public IActionResult Update(int id, Product updatedProduct)
    {
        Product? existingProduct =
            Products.FirstOrDefault(p => p.Id == id);

        if (existingProduct == null)
        {
            return NotFound();
        }

        if (updatedProduct.Id != 0 && updatedProduct.Id != id)
        {
            return BadRequest("The route ID and product ID must match.");
        }

        if (string.IsNullOrWhiteSpace(updatedProduct.Name) ||
            updatedProduct.Price < 0 ||
            updatedProduct.Stock < 0)
        {
            return BadRequest("Invalid product data.");
        }

        existingProduct.Name = updatedProduct.Name;
        existingProduct.Price = updatedProduct.Price;
        existingProduct.Stock = updatedProduct.Stock;

        return NoContent();
    }


    [HttpDelete("{id:int}")]
    public IActionResult Delete(int id)
    {
        Product? product = Products.FirstOrDefault(p => p.Id == id);

        if (product == null)
        {
            return NotFound();
        }

        Products.Remove(product);

        return NoContent();
    }
}
